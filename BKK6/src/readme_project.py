 for ax,s in zip(axs[0],panels):
  if s['kind']=='heatmap':
   a=np.array(s['values']);im=ax.imshow(a,aspect='auto',cmap=s.get('cmap','Blues'),vmin=s.get('vmin'),vmax=s.get('vmax'))
   ax.set_xticks(range(len(s['categories'])),[translate(x) for x in s['categories']]);ax.set_yticks(range(len(s['rows'])),s['rows'])
